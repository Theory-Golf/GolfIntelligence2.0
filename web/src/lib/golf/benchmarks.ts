// Longest yardage covered by the men's tables; the women's tables run to 620.
// Distances beyond a table's coverage clamp to its longest row.
const MAX_DIST = 700;
// Putt column is populated 0–90 ft; beyond that, use the plateau value.
const MAX_PUTT_DIST = 90;
const PUTT_PLATEAU = 1.99;

function lookupBenchmark(lookup: BenchmarkLookup, distance: number, location: string): number {
  if (distance <= 0) return 0; // ball in hole — 0 strokes needed
  const d = Math.max(1, Math.min(MAX_DIST, Math.round(distance)));
  switch (location) {
    case 'Tee':      return lookup.tee[d]      ?? lookup.tee[lookup.tee.length - 1]      ?? 0;
    case 'Fairway':  return lookup.fairway[d]  ?? lookup.fairway[lookup.fairway.length - 1]  ?? 0;
    case 'Rough':    return lookup.rough[d]    ?? lookup.rough[lookup.rough.length - 1]    ?? 0;
    case 'Sand':     return lookup.sand[d]     ?? lookup.sand[lookup.sand.length - 1]     ?? 0;
    case 'Recovery': return lookup.recovery[d] ?? lookup.recovery[lookup.recovery.length - 1] ?? 0;
    case 'Green':
    case 'Putt': {
      const puttDist = Math.min(d, MAX_PUTT_DIST);
      return lookup.putt[puttDist] ?? PUTT_PLATEAU;
    }
    default:         return lookup.fairway[d]  ?? lookup.fairway[lookup.fairway.length - 1]  ?? 0;
  }
}

/**
 * Look up expected strokes from a benchmark table
 */
export function lookupExpectedStrokes(
  benchmark: BenchmarkSelection,
  distance: number,
  location: string
): number {
  return lookupBenchmark(BENCHMARK_LOOKUPS[benchmark.gender][benchmark.tier], distance, location);
}

/**
 * Expected make rate (%) from a given putt distance, derived from the selected
 * benchmark's own expected-strokes table.
 *
 * Expected putts from d feet decompose as E(d) = p + (1 - p)(1 + R(d)), where p
 * is the make rate and R(d) is the expected cost of holing out from wherever a
 * miss finishes. Solving for p:
 *
 *   p(d) = 1 - (E(d) - 1) / R(d)
 *
 * R(d) starts at a tap-in (1.03 strokes) and grows quadratically as misses
 * finish further from the hole. Calibrated against published PGA Tour make
 * rates, this reproduces the men's Tour table within ~1.5 points from 3-50 ft
 * (see benchmarks.test.ts). Because it reads whichever tier and gender are
 * selected, it tracks the benchmark dropdown automatically.
 *
 * Accuracy degrades past ~50 ft, where the make rate is near zero for every
 * tier and callers should treat it as "no meaningful expectation" rather than a
 * target.
 */
export function expectedMakeRate(benchmark: BenchmarkSelection, distanceFt: number): number {
  if (distanceFt <= 0) return 100;
  const expected = lookupExpectedStrokes(benchmark, distanceFt, 'Putt');
  // Past 50 ft the leave model would grow faster than the expected-strokes
  // curve, nudging the derived make rate back up. Every tier is already at
  // roughly zero there, so the miss cost holds at its 50 ft value and the curve
  // stays monotonic.
  const leaveRef = Math.min(distanceFt, 50);
  const missCost = Math.max(1.03, 1 + 0.00007 * leaveRef * leaveRef);
  const rate = 1 - (expected - 1) / missCost;
  return Math.max(0, Math.min(1, rate)) * 100;
}

/**
 * Calculate Strokes Gained for a single shot
 * SG = Expected from Start - (1 + Expected from End)
 * For penalty shots: SG = Expected from Start - (2 + Expected from End)
 * The extra "-1" accounts for the penalty stroke
 */
export function calculateStrokesGained(
  benchmark: BenchmarkSelection,
  startDistance: number,
  startLocation: string,
  endDistance: number,
  endLocation: string,
  isPenalty: boolean = false
): number {
  const expectedStart = lookupExpectedStrokes(benchmark, startDistance, startLocation);
  const expectedEnd = lookupExpectedStrokes(benchmark, endDistance, endLocation);

  // For penalty shots, subtract an extra stroke (penalty stroke)
  const penaltyAdjustment = isPenalty ? 1 : 0;

  // SG = Expected from start position - (1 + expected from end position + penalty adjustment)
  return expectedStart - (1 + expectedEnd + penaltyAdjustment);
}

